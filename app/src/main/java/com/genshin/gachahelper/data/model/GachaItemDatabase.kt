    /**
     * 根据物品名称和类型推断稀有度
     *
     * @param itemName 物品名称
     * @param itemTypeStr 物品类型字符串（"角色" 或 "武器"）
     * @return 推断的稀有度（5/4/3），无法确定时返回 3
     */
    fun inferRarity(itemName: String, itemTypeStr: String): Int {
        val isCharacter = itemTypeStr.contains("角色") ||
            itemTypeStr.equals("character", true)
        val isWeapon = itemTypeStr.contains("武器") ||
            itemTypeStr.equals("weapon", true)

        return when {
            // 角色至少为 4 星
            isCharacter -> {
                if (itemName in FIVE_STAR_CHARACTERS) 5 else 4
            }
            // 武器检查五星和四星列表
            isWeapon -> {
                when {
                    itemName in FIVE_STAR_WEAPONS -> 5
                    itemName in FOUR_STAR_WEAPONS -> 4
                    else -> 3
                }
            }
            // 未知类型，按名称检查
            else -> {
                when {
                    itemName in FIVE_STAR_CHARACTERS -> 5
                    itemName in FIVE_STAR_WEAPONS -> 5
                    itemName in FOUR_STAR_WEAPONS -> 4
                    else -> 3
                }
            }
        }
    }
